import type { HTMLAttributes } from 'react';
import { forwardRef } from 'react';
import { cn } from '../../lib/utils';

export interface CardProps extends HTMLAttributes<HTMLDivElement> {
  variant?: 'default' | 'glass' | 'bordered';
  hover?: boolean;
}

export const Card = forwardRef<HTMLDivElement, CardProps>(
  ({ className, variant = 'default', hover = false, children, ...props }, ref) => {
    const variants = {
      default: 'bg-bg-card border border-border-primary',
      glass: 'glass',
      bordered: 'bg-bg-card border-2 border-border-secondary',
    };

    const hoverStyles = hover
      ? 'transition-all duration-300 hover:border-border-secondary hover:shadow-lg'
      : '';

    return (
      <div
        ref={ref}
        className={cn('rounded-xl', variants[variant], hoverStyles, className)}
        {...props}
      >
        {children}
      </div>
    );
  }
);

Card.displayName = 'Card';

